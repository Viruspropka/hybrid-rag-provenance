"""Regenerate RESULTS.md and the README evaluation block from run folders.

Every number written here is read from ``eval/runs/<run>/metrics.json``; nothing
is typed by hand. Numbers are truncated (not rounded) to three decimals, so a
printed value is never higher than the measured one.

* The headline is the latest full run of the default offline profile.
* Each other profile (a neural embedder, a cross-encoder) gets its own section
  from its latest committed run; a profile without a run is listed as "not run".
* One-line explanations of failure cases come from ``eval/failure_notes.json``
  (written by a person after reading the run); a miss without a note gets an
  automatic description of what happened.
"""

from __future__ import annotations

import json
import math
from pathlib import Path

DEFAULT_PROFILE = "hashing-512+overlap"
TAGS = ("keyword-heavy", "paraphrase", "multi-hop", "stale-vs-fresh", "unanswerable")
README_BEGIN = "<!-- eval-results:begin (generated by eval/report.py) -->"
README_END = "<!-- eval-results:end -->"

# Profiles that are documented as not run when no committed run exists for them.
NOT_RUN = {
    "st:BAAI/bge-m3": "about 2.2 GB of weights; run it with `make eval-bge-m3` (downloads the model once)",
}


def t3(x: float | None) -> str:
    """Truncate to three decimals: 0.8889 -> 0.888, never rounded up."""
    if x is None:
        return "n/a"
    return f"{math.floor(x * 1000 + 1e-9) / 1000:.3f}"


def load_runs(runs_dir: Path) -> list[dict]:
    out = []
    for d in sorted(p for p in runs_dir.iterdir() if p.is_dir()) if runs_dir.is_dir() else []:
        m, e = d / "metrics.json", d / "environment.json"
        if m.is_file() and e.is_file():
            out.append({"dir": d, "metrics": json.loads(m.read_text(encoding="utf-8")),
                        "env": json.loads(e.read_text(encoding="utf-8")), "raw": m.read_bytes()})
    return out


def per_question(run: dict) -> list[dict]:
    path = run["dir"] / "per_question.jsonl"
    return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]


def note_statuses(root: Path) -> dict[str, str]:
    import sys
    sys.path.insert(0, str(root / "src"))
    from hybrid_rag.config import SAMPLE_VAULT
    from hybrid_rag.notes import parse_frontmatter
    out = {}
    for p in SAMPLE_VAULT.rglob("*.md"):
        if p.name != "README.md":
            fm, _ = parse_frontmatter(p.read_text(encoding="utf-8"))
            out[fm.id] = fm.status or "active"
    return out


# ------------------------------------------------------------- tables
def retrieval_table(m: dict) -> str:
    lines = ["| Configuration | recall@1 | recall@5 | recall@10 | MRR@10 |", "|---|---:|---:|---:|---:|"]
    for c in m["configs"]:
        o = m["retrieval"][c["id"]]["overall"]
        lines.append(f"| {c['name']} | {t3(o['recall@1'])} | {t3(o['recall@5'])} | {t3(o['recall@10'])} "
                     f"| {t3(o['mrr@10'])} |")
    return "\n".join(lines)


def tag_table(m: dict, metric: str) -> str:
    tags = [t for t in TAGS if t != "unanswerable" and m["tag_counts"].get(t)]
    head = "| Configuration | " + " | ".join(f"{t} (n={m['tag_counts'][t]})" for t in tags) + " |"
    lines = [head, "|---|" + "---:|" * len(tags)]
    for c in m["configs"]:
        bt = m["retrieval"][c["id"]]["by_tag"]
        lines.append(f"| {c['name']} | " + " | ".join(t3(bt[t][metric]) for t in tags) + " |")
    return "\n".join(lines)


ANSWER_ROWS = (
    ("answered_rate", "Answered (answerable questions)", "share of answerable questions not abstained on"),
    ("citation_precision", "Citation precision", "cited notes that are gold notes, over answered questions"),
    ("citation_recall", "Citation recall", "required citations that were cited, over all answerable (abstain = 0)"),
    ("citations_in_retrieved_rate", "Citations inside the retrieved set", "answers whose every citation is in the top-5 chunks"),
    ("faithfulness_proxy", "Faithfulness proxy", "answer sentences with >= 0.6 token overlap with a cited passage"),
    ("answer_term_recall", "Gold-answer term recall", "content terms of the gold answer found in the answer (abstain = 0)"),
    ("unanswerable_abstention_rate", "Abstained on unanswerable", "share of unanswerable questions answered with \"no answer\""),
)


def answer_table(a: dict) -> str:
    o = a["overall"]
    lines = ["| Metric | Value | Definition |", "|---|---:|---|"]
    for key, label, desc in ANSWER_ROWS:
        lines.append(f"| {label} | {t3(o.get(key))} | {desc} |")
    return "\n".join(lines)


def sweep_table(a: dict) -> str:
    lines = ["| Abstain below coverage | Retriever low-confidence flag | Answered | Citation precision "
             "| Citation recall | Gold-answer term recall | Abstained on unanswerable |",
             "|---:|---|---:|---:|---:|---:|---:|"]
    for s in a.get("sweep", []):
        lines.append(f"| {s['abstain_below']:.2f} | {'used' if s['retriever_flag'] else 'ignored'} "
                     f"| {t3(s.get('answered_rate'))} | {t3(s.get('citation_precision'))} "
                     f"| {t3(s.get('citation_recall'))} | {t3(s.get('answer_term_recall'))} "
                     f"| {t3(s.get('unanswerable_abstention_rate'))} |")
    return "\n".join(lines)


def run_meta(run: dict, identical: list[str] | None = None) -> str:
    m, e = run["metrics"], run["env"]
    mc = e["machine"]
    dirty = e.get("uncommitted_changes") or []
    state = "clean tree" if not dirty else f"uncommitted changes in {', '.join(dirty)}"
    lines = [
        f"- Run folder: [`eval/runs/{run['dir'].name}/`](eval/runs/{run['dir'].name}/) "
        "(`run.log`, `per_question.jsonl`, `metrics.json`, `environment.json`)",
        f"- Command: `{e['command']}`",
        f"- Seed: {m['seed']}; reference date for the freshness clock: {m['reference_date']}",
        f"- Code commit: `{e['commit']}` ({state})",
        f"- Date (UTC): {e['started_utc']}",
        f"- Machine: {mc['cpu']}, {mc['cpu_count']} cores; {mc['os']}; Python {mc['python']}; "
        f"SQLite {mc['sqlite']}",
        f"- Embedder: `{m['embedder']}`; reranker in the reranker row: `{m['reranker']}`",
        f"- Question set: `{m['questions_file']}` sha256 `{m['questions_sha256']}` "
        f"({m['n_questions']} questions: " + ", ".join(f"{t} {n}" for t, n in m["tag_counts"].items()) + ")",
        f"- Wall time: {e['wall_seconds']} s",
    ]
    pk = e.get("packages") or {}
    if pk:
        lines.append("- Packages: " + ", ".join(f"{k} {v}" for k, v in sorted(pk.items())))
    if identical is not None:
        lines.append("- Determinism: " + (
            f"`metrics.json` is byte-identical in the runs {', '.join(f'`{x}`' for x in identical)}"
            if identical else "only one run of this profile so far"))
    return "\n".join(lines)


# ------------------------------------------------------------ failures
def failure_cases(run: dict, root: Path) -> str:
    notes_path = root / "eval" / "failure_notes.json"
    notes = json.loads(notes_path.read_text(encoding="utf-8")) if notes_path.is_file() else {}
    statuses = note_statuses(root)
    rows = per_question(run)
    config = run["metrics"]["answer"]["config"]
    retr = [r for r in rows if r["kind"] == "retrieval" and r["config"] == config and r["gold"]
            and r["mrr@10"] < 1.0]
    lines = [f"Configuration `{config}` (the system default: hybrid RRF k=20 + provenance). Explanations "
             "come from `eval/failure_notes.json`; entries marked *(auto)* are generated from the run.",
             "", "### Retrieval: gold note not at rank 1", "",
             "| Question | Gold | Came back (top 3) | Gold rank | Why |", "|---|---|---|---:|---|"]
    for r in retr:
        why = notes.get(r["id"])
        if not why:
            hidden = [g for g in r["gold"] if statuses.get(g) in ("archived", "superseded")]
            if hidden and not r["historical"]:
                why = (f"*(auto)* gold note is {statuses[hidden[0]]}; the status filter hides it because the "
                       "question is not phrased as historical")
            elif r["first_gold_rank"] is None:
                why = "*(auto)* gold note not in the top 10"
            else:
                why = f"*(auto)* `{r['top'][0]}` ranked above the gold note"
        lines.append(f"| `{r['id']}` | {', '.join(r['gold'])} | {', '.join(r['top'][:3])} "
                     f"| {r['first_gold_rank'] or '>10'} | {why} |")
    answers = [r for r in rows if r["kind"] == "answer"]
    wrong = [a for a in answers if not a["check"]["abstained"] and (
        not a["check"]["answerable"] or a["check"].get("citation_precision", 1) < 1
        or a["check"].get("citation_recall", 1) < 1)]
    lines += ["", "### Answers: wrong or missing citations, answered unanswerables", "",
              "| Question | Tag | Gold | Cited | Why |", "|---|---|---|---|---|"]
    for a in wrong:
        why = notes.get(f"{a['id']}:answer")
        if not why:
            why = ("*(auto)* answered a question the vault cannot answer" if not a["check"]["answerable"]
                   else "*(auto)* cited a non-gold note" if a["check"]["citation_precision"] < 1
                   else "*(auto)* a required citation is missing")
        lines.append(f"| `{a['id']}` | {a['tag']} | {', '.join(a['gold']) or '(none)'} "
                     f"| {', '.join(a['answer']['citations'])} | {why} |")
    abst = [a for a in answers if a["check"]["answerable"] and a["check"]["abstained"]]
    lines += ["", f"### Answers: abstained on an answerable question ({len(abst)})", "",
              "| Question | Tag | Reason given by the answerer |", "|---|---|---|"]
    for a in abst:
        lines.append(f"| `{a['id']}` | {a['tag']} | {a['answer']['reason']} |")
    return "\n".join(lines)


# --------------------------------------------------------------- main
def regenerate(root: Path) -> list[Path]:
    runs = load_runs(root / "eval" / "runs")
    full = [r for r in runs if not r["metrics"].get("subset")]
    default = [r for r in full if r["metrics"]["profile"] == DEFAULT_PROFILE]
    if not default:
        raise SystemExit("no full run of the default profile in eval/runs; run `make eval` first")
    primary = default[-1]
    identical = [r["dir"].name for r in default if r["raw"] == primary["raw"]]
    m = primary["metrics"]
    others: dict[str, dict] = {}
    for r in full:
        if r["metrics"]["profile"] != DEFAULT_PROFILE:
            others[r["metrics"]["profile"]] = r
    n_ans = m["n_answerable"]
    out = [
        "# Evaluation results",
        "",
        f"<!-- Generated by eval/report.py from eval/runs/{primary['dir'].name}/. Do not edit by hand. -->",
        "",
        "Retrieval and answer quality of this repository on its own **synthetic** sample vault (21 fictional "
        f"notes) and a frozen set of {m['n_questions']} labelled questions ([eval/questions.jsonl]"
        "(eval/questions.jsonl), sources in [eval/DATA_SOURCES.md](eval/DATA_SOURCES.md)). Every number below is "
        "read from a committed run folder under `eval/runs/`; values are truncated to three decimals.",
        "",
        "Reproduce: `make eval` (runs `python -m eval.run --seed 42`): offline, no API keys, no model "
        "download, a socket guard fails the run on any network access. Its wall time is in the run metadata.",
        "",
        "## Headline run (offline profile)",
        "",
        run_meta(primary, identical),
        "",
        f"## Retrieval ({n_ans} answerable questions)",
        "",
        "Rankings are scored at note level (chunks collapsed to their note, first appearance wins). "
        "recall@k = share of a question's gold notes in the top k, averaged; MRR@10 = 1 / rank of the first "
        "gold note within the top 10, else 0. Multi-hop questions have two gold notes, so their recall@1 is "
        "at most 0.5. Unanswerable questions are excluded here and scored in the answer section. The "
        "exact-key fast path is off so the retrievers themselves are measured. \"Provenance\" = status filter "
        "plus the score multipliers of the provenance layer.",
        "",
        retrieval_table(m),
        "",
        "### By tag: MRR@10",
        "",
        tag_table(m, "mrr@10"),
        "",
        "### By tag: recall@1",
        "",
        tag_table(m, "recall@1"),
        "",
        "### By tag: recall@5",
        "",
        tag_table(m, "recall@5"),
        "",
        f"## Answers and citations ({m['answer']['overall']['n_answerable']} answerable, "
        f"{m['answer']['overall']['n_unanswerable']} unanswerable)",
        "",
        "A deterministic extractive answerer ([eval/answer.py](eval/answer.py)) reads the top 5 chunks of "
        "the default configuration (hybrid RRF + provenance), returns the one or two sentences that cover most "
        "question terms and cites their notes. It abstains when the retriever flags low confidence or when no "
        "sentence covers half of the question's content terms (thresholds fixed before the first run). A "
        "rule-based checker scores the answer. The faithfulness number is a **proxy** (token overlap, not "
        "entailment); for an extractive answerer that copies sentences it is a sanity check and should be "
        "1.0. No LLM is involved in any number on this page.",
        "",
        answer_table(m["answer"]),
        "",
        "### Abstention threshold sweep",
        "",
        "The headline uses the pre-registered setting (0.50, flag used). The sweep shows the trade-off "
        "between answering more and abstaining on unanswerable questions; it was not used to pick the setting.",
        "",
        sweep_table(m["answer"]),
        "",
        "### Answers by tag",
        "",
        "| Tag | Answered | Citation precision | Citation recall | Gold-answer term recall | "
        "Abstained on unanswerable |",
        "|---|---:|---:|---:|---:|---:|",
    ]
    for t in TAGS:
        b = m["answer"]["by_tag"].get(t, {})
        out.append(f"| {t} | {t3(b.get('answered_rate'))} | {t3(b.get('citation_precision'))} "
                   f"| {t3(b.get('citation_recall'))} | {t3(b.get('answer_term_recall'))} "
                   f"| {t3(b.get('unanswerable_abstention_rate'))} |")
    out += ["", "## Other profiles (optional neural models)", ""]
    if not others:
        out.append("No committed run.")
    for prof, r in sorted(others.items()):
        rm = r["metrics"]
        o = rm["answer"]["overall"]
        out += [f"### `{rm['embedder']}` + reranker `{rm['reranker']}`", "",
                "Needs `pip install -e \".[models]\"` and a one-time model download from Hugging Face "
                "(no key). Same question set, seed and checker; only the embedder and the reranker differ.", "",
                run_meta(r), "- Determinism: checked for the offline profile only; this profile was run once "
                "(CPU inference, so repeated runs are expected but not verified to match)", "",
                retrieval_table(rm), "",
                "MRR@10 by tag:", "", tag_table(rm, "mrr@10"), "",
                f"Answers (same extractive answerer on this profile's hybrid + provenance ranking): answered "
                f"{t3(o.get('answered_rate'))}, citation precision {t3(o.get('citation_precision'))}, citation "
                f"recall {t3(o.get('citation_recall'))}, gold-answer term recall {t3(o.get('answer_term_recall'))}, "
                f"abstained on unanswerable {t3(o.get('unanswerable_abstention_rate'))}.", ""]
    for emb, reason in NOT_RUN.items():
        if not any(r["metrics"]["embedder"] == emb for r in others.values()):
            out += [f"### `{emb}`: not run", "", f"Reason: {reason}. No number for it appears anywhere in "
                    "this repository.", ""]
    out += ["## Failure cases", "", failure_cases(primary, root), "",
            "## Honest limits", "",
            f"- 21 synthetic notes and {m['n_questions']} questions written by the author of the code, who also chose the "
            "provenance defaults while looking at the same vault. This is a reproducible illustration of the "
            "mechanism, not a benchmark; the numbers do not transfer to real corpora.",
            "- The offline profile's \"dense\" side is a feature-hashing embedder: lexical, not semantic. It "
            "makes the run deterministic and download-free and is weak on paraphrases by construction. The "
            "reranker in the offline profile is a lexical overlap scorer, a stand-in for a cross-encoder.",
            "- The faithfulness metric is a token-overlap proxy. It catches invented sentences and wrong "
            "citations, not a sentence that reuses a passage's words to state something false.",
            "- Gold-answer term recall counts content words, so a correct answer phrased differently can score "
            "low and a wrong sentence that happens to contain the words can score high.",
            f"- One question set, one seed; there are no confidence intervals. With {n_ans} answerable questions "
            f"one single-gold question moves recall@1 by 1/{n_ans}.",
            "- An optional LLM-as-judge mode is not implemented; nothing here depends on a hosted model.",
            ""]
    results = root / "RESULTS.md"
    results.write_text("\n".join(out), encoding="utf-8")
    written = [results]

    readme = root / "README.md"
    text = readme.read_text(encoding="utf-8")
    if README_BEGIN in text and README_END in text:
        o = m["answer"]["overall"]
        block = "\n".join([
            README_BEGIN,
            f"Offline profile (`{m['embedder']}` embedder, `{m['reranker']}` reranker), {n_ans} answerable "
            f"questions, run `eval/runs/{primary['dir'].name}/`, code `{primary['env']['commit'][:12]}`:",
            "",
            retrieval_table(m),
            "",
            f"Extractive answers on the default configuration: citation precision "
            f"{t3(o.get('citation_precision'))}, citation recall {t3(o.get('citation_recall'))}, faithfulness "
            f"proxy {t3(o.get('faithfulness_proxy'))}, abstained on {t3(o.get('unanswerable_abstention_rate'))} "
            f"of the unanswerable questions and on {t3(o.get('false_abstention_rate'))} of the answerable ones.",
            README_END,
        ])
        start = text.index(README_BEGIN)
        end = text.index(README_END) + len(README_END)
        readme.write_text(text[:start] + block + text[end:], encoding="utf-8")
        written.append(readme)
    return written


if __name__ == "__main__":
    _root = Path(__file__).resolve().parents[1]
    for _p in regenerate(_root):
        print(f"regenerated {_p.relative_to(_root)}")
